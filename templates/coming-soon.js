/**
 * قالب توليد صفحات الدول قيد الإعداد (قريباً)
 */

const { escapeHtml } = require('./country');

function renderComingSoonPage(page, shared, ctx) {
    const { assetHashes, activeCountries } = ctx;
    const canonicalUrl = `${shared.siteUrl}/${page.slug}/`;
    const ogImageUrl = `${shared.siteUrl}/assets/images/kaaba.jpg`;
    const desc = `${page.heading} — قريباً ضمن دليل السفر البري الشامل إلى مكة المكرمة.`;

    // روابط الأدلة المتاحة تُشتق من الدول الفعّالة، فلا تحتاج تعديلاً عند إضافة دولة
    const activeLinksHtml = activeCountries.map(c =>
        `                <a href="../${escapeHtml(c.slug)}/" class="btn-station-map">تصفح دليل ${escapeHtml(c.countryName)}</a>`
    ).join('\n');

    return `<!-- AUTO-GENERATED BY build.js - DO NOT EDIT MANUALLY -->
<!DOCTYPE html>
<html lang="ar" dir="rtl">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
    <meta name="robots" content="noindex, follow">
    <meta name="description" content="${escapeHtml(desc)}">
    <title>${escapeHtml(page.pageTitle)}</title>
    <link rel="canonical" href="${escapeHtml(canonicalUrl)}">
    <meta property="og:type" content="website">
    <meta property="og:locale" content="ar_AR">
    <meta property="og:title" content="${escapeHtml(page.pageTitle)}">
    <meta property="og:description" content="${escapeHtml(desc)}">
    <meta property="og:url" content="${escapeHtml(canonicalUrl)}">
    <meta property="og:image" content="${escapeHtml(ogImageUrl)}">
    <link rel="apple-touch-icon" href="../assets/images/apple-touch-icon.png">
    <link rel="icon" type="image/png" sizes="192x192" href="../assets/images/icon-192.png">
    <link href="https://fonts.googleapis.com/css2?family=Tajawal:wght@400;500;700;800;900&display=swap" rel="stylesheet">
    <link rel="stylesheet" href="../css/style.css?v=${escapeHtml(assetHashes.styleCss)}">
</head>
<body>
    <div class="container coming-soon">
        <div class="route-card coming-soon-card">
            <div class="coming-soon-icon">🕋</div>
            <h1 class="coming-soon-title">${escapeHtml(page.heading)}</h1>
            <p class="coming-soon-text">جاري العمل على إعداد وتدقيق محطات ومسارات هذا الدليل ليظهر بأفضل صورة قريباً بإذن الله.</p>
            <div class="coming-soon-actions">
                <a href="../" class="btn-launch">🏠 العودة للرئيسية</a>
${activeLinksHtml}
            </div>
        </div>
    </div>
</body>
</html>
`;
}

module.exports = {
    renderComingSoonPage
};
