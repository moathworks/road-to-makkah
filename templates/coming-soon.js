/**
 * قالب صفحات الدول قيد الإعداد «قريباً» (بالعربية أو الإنجليزية حسب ctx.lang)
 */

const { escapeHtml, tr, makeT, renderHead, renderLangSwitch, LANG_META } = require('./helpers');

function renderComingSoonPage(page, shared, ctx) {
    const { assetHashes, activeCountries, lang } = ctx;
    const t = makeT(lang);
    const countryName = tr(page.countryName, lang);
    const pageTitle = t('soon.titleDefault', { country: countryName });
    const heading = page.heading ? tr(page.heading, lang) : pageTitle;

    // روابط الأدلة المتاحة تُشتق من الدول الفعّالة، فلا تحتاج تعديلاً عند إضافة دولة
    const activeLinksHtml = activeCountries.map(c =>
        `                <a href="../${escapeHtml(c.slug)}/" class="btn-station-map">${escapeHtml(t('soon.browse', { country: tr(c.countryName, lang) }))}</a>`
    ).join('\n');

    const head = renderHead({
        lang,
        slug: page.slug,
        title: pageTitle,
        description: t('soon.description', { heading }),
        siteName: t('site.name'),
        siteUrl: shared.siteUrl,
        themeColor: '#121212',
        robots: 'noindex, follow',
        stylesheet: `css/style.css?v=${assetHashes.styleCss}`,
        fontsStylesheet: `css/fonts.css?v=${assetHashes.fontsCss}`
    });

    return `<!-- AUTO-GENERATED BY build.js - DO NOT EDIT MANUALLY -->
<!DOCTYPE html>
<html lang="${lang}" dir="${LANG_META[lang].dir}">
<head>
${head}
</head>
<body>
    <div class="container coming-soon">
        <div class="route-card coming-soon-card">
            <div class="coming-soon-icon">🕋</div>
            <h1 class="coming-soon-title">${escapeHtml(heading)}</h1>
            <p class="coming-soon-text">${escapeHtml(t('soon.text'))}</p>
            <div class="coming-soon-actions">
                <a href="../" class="btn-launch">${escapeHtml(t('soon.home'))}</a>
${activeLinksHtml}
                ${renderLangSwitch(page.slug, lang, 'btn-station-map')}
            </div>
        </div>
    </div>
</body>
</html>
`;
}

module.exports = {
    renderComingSoonPage
};
